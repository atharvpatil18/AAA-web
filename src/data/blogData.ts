export function getLocalizedBlogPost(post: BlogPost, lang: string): BlogPost {
  if (lang !== "hi" && lang !== "mr") return post;
  const locData = POST_LOCALIZATIONS[post.id]?.[lang as "hi" | "mr"];
  if (!locData) return post;
  return {
    ...post,
    ...locData,
    poll: locData.poll || post.poll
  };
}

